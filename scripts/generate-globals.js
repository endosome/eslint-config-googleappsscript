// Writes globals.js from the global variables that @types/google-apps-script declares
// (SpreadsheetApp, Logger, the advanced services, ...). Run it with `npm run generate` after the types change.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const typesDirectory = fileURLToPath(new URL('../node_modules/@types/google-apps-script/', import.meta.url));
const outputFile = fileURLToPath(new URL('../globals.js', import.meta.url));

// declared as variables for the typings only, they do not exist at runtime
const notGlobals = new Set(['Date2']);

const declarationFiles = directory =>
  readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const entryPath = path.join(directory, entry.name);

    if (entry.isDirectory()) {
      return declarationFiles(entryPath);
    }

    return entry.name.endsWith('.d.ts') ? [entryPath] : [];
  });

export const collectGlobals = () => {
  const names = new Set();

  for (const file of declarationFiles(typesDirectory)) {
    for (const match of readFileSync(file, 'utf8').matchAll(/^declare var ([A-Za-z_$][\w$]*):/gm)) {
      if (!notGlobals.has(match[1])) {
        names.add(match[1]);
      }
    }
  }

  return [...names].sort((a, b) => a.localeCompare(b, 'en'));
};

export const render = names => `// Generated by scripts/generate-globals.js from @types/google-apps-script, do not edit.
export default {
${names.map(name => `  ${name}: 'readonly',`).join('\n')}
};
`;

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const names = collectGlobals();

  writeFileSync(outputFile, render(names));
  process.stdout.write(`${names.length} globals written to globals.js\n`);
}
